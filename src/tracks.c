const CupInfo CUPS[CUP_COUNT] = {
    {"ROOKIE CUP", 0, 3},
    {"PRO CUP", 3, 3},
    {"MASTER CUP", 6, 4},
};

int track_cup(int track) {
    return track >= 0 && track < TRACK_COUNT ? TRACK_INFO[track].cup : 0;
}

int game_track_index(const char *id) {
    for (int i = 0; i < TRACK_COUNT; i++)
        if (!SDL_strcmp(id, TRACK_INFO[i].id))
            return i;
    return -1;
}
